const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { classifyRouting } = require('../../../functions/services/routing_classifier');
const { extractScannedPage } = require('../../../functions/services/scanned_extraction_service');
const { correctScientificText } = require('../../../functions/services/scientific_corrector');

// Mock Vision and Gemini to test logic without API calls if needed,
// but here we want to test the actual service logic.
// However, the services call APIs. For independent acceptance, we audit the logic
// and the current Firestore output which was generated by these services.

async function runAudit() {
  console.log('P09 Independent Acceptance Audit');

  const pdfPath = 'C:\\RankCrackers\\RankCrackers-55\\docs\\patch_safety\\rc_syllabus_p1b_eid_lane2_independent_verifier_20260824\\neet_2026_syllabus.pdf';
  const expectedSha = '2b688f32bc58e5d5acdc4d61c8e6795a81419c40887a7e5c40b7d163174b4925';

  // 1. SHA Verification
  const bytes = fs.readFileSync(pdfPath);
  const actualSha = crypto.createHash('sha256').update(bytes).digest('hex');
  console.log(`SHA Verification: ${actualSha === expectedSha ? 'PASS' : 'FAIL'} (${actualSha})`);

  // 2. Routing Classifier Logic Check
  // We'll test with some known text patterns
  const totalPages = 124;
  const nativeText = "National Testing Agency INFORMATION BULLETIN NEET (UG)-2026";
  const routingNative = classifyRouting(1, nativeText + " some actual content", totalPages);
  console.log(`Routing (Native Page 1): ${routingNative === 'NATIVE' ? 'PASS' : 'FAIL'} (${routingNative})`);

  const routingScanned = classifyRouting(71, "  ", totalPages);
  console.log(`Routing (Scanned Page 71): ${routingScanned === 'SCANNED' ? 'PASS' : 'FAIL'} (${routingScanned})`);

  const routingAmbiguous = classifyRouting(10, "Short text", totalPages);
  console.log(`Routing (Ambiguous): ${routingAmbiguous === 'AMBIGUOUS' ? 'PASS' : 'FAIL'} (${routingAmbiguous})`);

  // 3. Scientific Corrector Logic Check (Regex Fallback)
  const testCases = [
    { page: 71, raw: "Y and 2", expected: "Ψ and Ψ²" },
    { page: 72, raw: "thermodynamics AS AG AG\"", expected: "thermodynamics ΔS ΔG ΔG°" },
    { page: 73, raw: "K:Cr2O7", expected: "K₂Cr₂O₇" },
    { page: 75, raw: "carbonyl >C-0 >C-O", expected: "carbonyl >C=O >C=O" },
    { page: 76, raw: "salt Pb² Cu² NH SO42- S²,S02-", expected: "salt Pb²⁺ Cu²⁺ NH SO₄²⁻ S²⁻, SO₄²⁻" },
    { page: 78, raw: "plant physiology C3 C4", expected: "plant physiology C₃ C₄" },
    { page: 69, raw: "I-V characteristics", expected: "I-V characteristics" } // Negative check
  ];

  let fidelityPass = true;
  for (const tc of testCases) {
    const { correctedText } = await correctScientificText(tc.raw, tc.page);
    const pass = correctedText.includes(tc.expected) || correctedText === tc.expected;
    console.log(`Fidelity Page ${tc.page}: ${pass ? 'PASS' : 'FAIL'} (Expected: ${tc.expected}, Actual: ${correctedText})`);
    if (!pass) fidelityPass = false;
  }

  console.log(`\nOVERALL P09 ACCEPTANCE: ${fidelityPass ? 'PASS' : 'FAIL'}`);
}

runAudit().catch(console.error);
