"use strict";

const JOB_STATE = Object.freeze({
  PENDING: "PENDING",
  SOURCE_CHECK: "SOURCE_CHECK",
  DRAFTING: "DRAFTING",
  REVIEW_PENDING: "REVIEW_PENDING",
  REVIEWING: "REVIEWING",
  APPROVED: "APPROVED",
  HELD_SOURCE: "HELD_SOURCE",
  HELD_REVIEW: "HELD_REVIEW",
  BLOCKED_TRANSIENTLY: "BLOCKED_TRANSIENTLY",
  FAILED: "FAILED",
});

const TERMINAL_STATES = new Set([
  JOB_STATE.APPROVED,
  JOB_STATE.HELD_SOURCE,
  JOB_STATE.HELD_REVIEW,
  JOB_STATE.FAILED,
]);

function isTerminal(state) {
  return TERMINAL_STATES.has(state);
}

module.exports = {
  JOB_STATE,
  TERMINAL_STATES,
  isTerminal,
};
