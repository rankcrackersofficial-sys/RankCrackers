  static String? getStateCode(String? stateName) {
    if (stateName == null || stateName.trim().isEmpty) return null;
    final trimmed = stateName.trim();
    // Direct match
    if (stateToCode.containsKey(trimmed)) return stateToCode[trimmed];
    // Case-insensitive match
    for (final entry in stateToCode.entries) {
      if (entry.key.toLowerCase() == trimmed.toLowerCase()) {
        return entry.value;
      }
    }
    // If it's already a valid 2-letter code
    final upper = trimmed.toUpperCase();
    if (codeToState.containsKey(upper)) return upper;
    return null;
  }

  static String? getStateName(String? stateCode) {
    if (stateCode == null || stateCode.trim().isEmpty) return null;
    final upper = stateCode.trim().toUpperCase();
    if (codeToState.containsKey(upper)) return codeToState[upper];
    for (final entry in stateToCode.entries) {
      if (entry.key.toLowerCase() == stateCode.trim().toLowerCase()) {
        return entry.key;
      }
    }
    return null;
  }

  static List<String> searchStates(String query) {
    if (query.trim().isEmpty) return statesAndUTs;
    final q = query.trim().toLowerCase();
    final startsWith = statesAndUTs.where((s) => s.toLowerCase().startsWith(q)).toList();
    final contains = statesAndUTs
        .where((s) => !s.toLowerCase().startsWith(q) && s.toLowerCase().contains(q))
        .toList();
    return [...startsWith, ...contains];
  }
